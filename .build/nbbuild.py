"""Notebook builder for the AI Engineer tutorial labs.

SPOILER WARNING: build scripts in this folder contain the reference solutions in
plain text. Learners should not open them.

    nb = Notebook(lab_id="lab_03_nlp_data_loader", title="Lab 3 — ...")
    nb.md("# ...")
    nb.code("...")
    nb.exercise("ex1", "Title", points=10, prompt="...", stub="...", tests="...", solution="...")
    nb.write(course_dir)

Each exercise emits: spec (markdown) -> stub cell (tagged) -> provided tests cell
(ends with lab.check) -> solution button cell. Solutions are written, encoded, to
<course>/.solutions/<lab_id>.json — never into the notebook.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from labkit import encode  # noqa: E402

SETUP = '''# ⚙️ Setup — run this first. It loads the grader (labkit) and your saved score.
import sys, pathlib
for _p in [pathlib.Path.cwd(), *pathlib.Path.cwd().parents]:
    if (_p / "labkit").is_dir():
        sys.path.insert(0, str(_p)); break
from labkit import Lab
lab = Lab("{lab_id}")'''


class Notebook:
    def __init__(self, lab_id, title):
        self.lab_id, self.title = lab_id, title
        self.cells, self.exercises = [], {}

    def _cell(self, kind, src, meta=None):
        c = {"cell_type": kind, "metadata": meta or {}, "source": src.strip("\n")}
        if kind == "code":
            c.update(execution_count=None, outputs=[])
        self.cells.append(c)

    def md(self, text):
        self._cell("markdown", text)

    def code(self, text):
        self._cell("code", text)

    def setup(self):
        self.code(SETUP.format(lab_id=self.lab_id))

    def mermaid(self, diagram, caption=None):
        body = "```mermaid\n" + diagram.strip("\n") + "\n```"
        if caption:
            body += f"\n\n*{caption}*"
        self.md(body)

    def figure(self, name, caption=None):
        """Embed figures/<name>.svg (generated by figures_lab_NN.py) with an optional caption."""
        alt = (caption or name).split(".")[0].replace('"', "'")
        body = f"![{alt}](figures/{name}.svg)"
        if caption:
            body += f"\n\n*{caption}*"
        self.md(body)

    def exercise(self, ex_id, title, points, prompt, stub, tests, solution, guide=None, guide_code=None):
        assert ex_id not in self.exercises, ex_id
        n = len(self.exercises) + 1
        self.exercises[ex_id] = {"title": title, "points": points, "solution": encode(solution.strip())}
        self.md(f"### 🎯 Exercise {n} — {title}  `({points} pts)`\n\n{prompt.strip()}\n\n"
                f"> ✍️ Read the guide below, write your answer in the stub cell, then run the **tests** cell under it. "
                f"Pass on your own: **+{points}**. Reveal the solution first: **−{points}**.")
        if guide:
            self.md("#### 🧰 What you need\n\n" + guide.strip())
        if guide_code:
            self.code("# 🔬 Building blocks: run and play with these (toy examples, not the answer)\n"
                      + guide_code.strip("\n"))
        self._cell("code", stub, {"labkit": {"role": "stub", "exercise": ex_id}, "tags": ["exercise"]})
        self._cell("code", tests.strip("\n") + "\n\n" + self._check_call(ex_id, tests),
                   {"labkit": {"role": "tests", "exercise": ex_id}})
        self._cell("code", f'lab.solution_button("{ex_id}")',
                   {"labkit": {"role": "solution", "exercise": ex_id}})

    @staticmethod
    def _check_call(ex_id, tests):
        names = [ln.split("def ", 1)[1].split("(")[0] for ln in tests.splitlines()
                 if ln.startswith("def test_")]
        return f'lab.check("{ex_id}", {", ".join(names)})'

    def write(self, course_dir, filename):
        course = Path(course_dir)
        (course / ".solutions").mkdir(parents=True, exist_ok=True)
        (course / ".solutions" / f"{self.lab_id}.json").write_text(
            json.dumps({"title": self.title, "exercises": self.exercises}, indent=1), encoding="utf-8")
        cells = []
        for c in self.cells:
            c = dict(c)
            c["source"] = c["source"].splitlines(keepends=True)
            cells.append(c)
        nb = {"cells": cells,
              "metadata": {"kernelspec": {"display_name": "Python (ai-engineer .venv)", "language": "python", "name": "ai-engineer"},
                           "language_info": {"name": "python", "pygments_lexer": "ipython3"}},
              "nbformat": 4, "nbformat_minor": 5}
        out = course / filename
        out.write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        total = sum(e["points"] for e in self.exercises.values())
        print(f"wrote {out} — {len(cells)} cells, {len(self.exercises)} exercises, {total} pts")
        return out
